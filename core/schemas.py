import uuid
from datetime import datetime
from typing import Dict, Any
from pydantic import BaseModel, Field, HttpUrl

# Namespace for deterministic UUIDs
NAMESPACE_ARTICLES = uuid.UUID('f0000000-0000-0000-0000-000000000000')

def generate_article_id(url: str) -> str:
    return str(uuid.uuid5(NAMESPACE_ARTICLES, url))

def generate_chunk_id(url: str, index: int) -> str:
    return str(uuid.uuid5(NAMESPACE_ARTICLES, f"{url}_{index}"))

class Article(BaseModel):
    url: HttpUrl
    title: str
    markdown_content: str
    timestamp: datetime = Field(default_factory=datetime.utcnow)
    
    @property
    def article_id(self) -> str:
        return generate_article_id(str(self.url))

class ArticleChunk(BaseModel):
    chunk_id: str
    parent_url: HttpUrl
    text: str
    metadata_headers: Dict[str, str]
    timestamp: datetime
    
    class Config:
        from_attributes = True

class CompanyProfile(BaseModel):
    company_name: str
    industry: str
    core_focus: str
    tone: str = "professional and insightful"

class RetrievedContext(BaseModel):
    url: HttpUrl
    title: str
    relevant_text: str

class BriefingItem(BaseModel):
    title: str = Field(..., description="Short, punchy title for the news item")
    summary: str = Field(..., max_length=1000, description="3-4 sentence explanation of the news")
    why_it_matters: str = Field(..., max_length=500, description="Context on how this impacts the specific company")
    source_url: HttpUrl

class SlackBriefing(BaseModel):
    header_text: str = Field(default="Weekly Intelligence Briefing")
    summary_text: str = Field(..., max_length=2000, description="Executive overview of the week")
    items: List[BriefingItem] = Field(..., max_length=5, description="Top 5 most relevant items")
    footer_text: str = Field(default="Generated by ArticlesAI Pipeline")
    
    @classmethod
    def quiet_week(cls):
        return cls(
            summary_text="No critical updates or significant news matched your focus areas this week.",
            items=[]
        )
    
    @classmethod
    def error_fallback(cls):
        return cls(
            summary_text="⚠️ Our AI pipeline encountered a system error while processing this week's briefing. Our engineers have been notified.",
            items=[]
        )
